_cache: dict = {}


def _die(msg: str):
    raise SystemExit(f"lexicon: {msg}")


def _en(kind: str) -> frozenset:
    hit = _cache.get(("en", kind))
    if hit is not None:
        return hit
    path = os.path.join(DATA_DIR, _EN_FILES[kind])
    if not os.path.isfile(path):
        _die(f"{path} is missing — broken checkout (build: python3 "
             "tools/build_en_words.py, see NOTICE)")
    words = set()
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if not line.startswith("#"):
                w = line.strip()
                if w:
                    words.add(w)
    out = _cache[("en", kind)] = frozenset(words)
    return out


def _morph():
    hit = _cache.get("morph")
    if hit is not None:
        return hit
    try:
        from natasha import MorphVocab
        m = MorphVocab()
    except Exception as e:                  # noqa: BLE001 — no package / broken
        _die(f"natasha is unavailable ({type(e).__name__}: {e}) — without Russian "
             "morphology the extra-replacement predicate does not work; install natasha "
             "or turn the feature off (cfg lexicon, "
             "LOCAL_VERDICT_PLAIN_GUARD=0)")
    _cache["morph"] = m
    return m


def _curated() -> frozenset:
    """Curated lists — plain without checks (IT terms, service fields,
    EN months, exceptions and international tools of the owner, legal forms)."""
    hit = _cache.get("curated")
    if hit is None:
        hit = _cache["curated"] = frozenset(
            {w.casefold() for w in TECH_TERMS | HEADINGS | MONTHS_EN | OWNER_KEEP
             | OWNER_TOOLS}
            | {w.casefold() for w in vocab.TECH_TERMS}
            | {w.casefold() for w in vocab.COMMON_EN}
            | {w.casefold() for w in vocab.LEGAL_FORMS})
    return hit


def name_evidence(word: str) -> bool:
    """The word has name evidence (see the module docstring): a known pymorphy
    parse with Name/Surn/Patr/Geox/Orgn/Trad, full-name dictionaries (first names, patronymics,
    surnames), an own SCOWL entry for Latin words."""
    w = word.strip()
    if _LAT.match(w):
        return w.casefold() in _en("proper")
    if not _CYR.match(w):
        return False
    for p in _morph().parse(w):
        if p.is_known and any(t in str(p.tag) for t in _PII_TAGS):
            return True
    from . import name_dicts
    return (name_dicts.is_first_name(w) or name_dicts.is_patronymic(w)
            or name_dicts.is_surname(w, _SURNAME_TOP))


def lc_dominant(word: str, freq) -> bool:
    """Corpus evidence of a common noun: lower-case ≥ LC_DOMINANCE ×
    upper-case (Capitalized + ALL CAPS) and ≥ LC_MIN. No frequency table — False."""
    if not freq:
        return False
    w = word.strip()
    lo = int(freq.get(w.lower(), 0) or 0)
    cap = w[:1].upper() + w[1:].lower()
    up = int(freq.get(cap, 0) or 0)
    if len(w) > 1:
        up += int(freq.get(w.upper(), 0) or 0)
    return lo >= LC_MIN and lo >= LC_DOMINANCE * max(up, 1)


def word_kind(word: str) -> str:
    """Class of ONE word: plain | name | unknown. name — there is name
    evidence (unmasked only by the corpus, see needs_model);
    unknown — outside the dictionaries (the previous rules decide)."""
    w = word.strip()
    if not w:
        return "unknown"
    cf = w.casefold()
    if cf in _curated() or is_owner_tool(w):
        return "plain"
    if name_evidence(w):
        return "name"
    if _LAT.match(w):
        return "plain" if cf in _en("words") else "unknown"
    if not _CYR.match(w):
        return "unknown"
    for p in _morph().parse(w):
        if p.is_known:
            return "plain"            # a known parse, no name one
    return "unknown"


def _words(literal: str) -> list:
    return [w for w in _SPLIT.split(str(literal or "").strip()) if w]


def is_plain(literal: str) -> bool:
    """The whole literal is ordinary vocabulary (every word is plain)."""
    lit = str(literal or "").strip()
    if not lit:
        return False
    if lit.casefold() in _curated() or is_owner_tool(lit):
        return True
    words = _words(lit)
    return bool(words) and all(word_kind(w) == "plain" for w in words)


REGRESS_FILE = "verdict_regress.tsv"
REGRESS_EXPECT = ("keep", "mask", "model", "model-mask")


def regress(path: str | None = None) -> dict:
    """The owner's rule regression set (data/verdict_regress.tsv):
    {form.strip().lower(): (expect, class, original form)}. A malformed line
    (not 2+ columns, expect outside keep|mask|model|model-mask, a duplicate form) =
    SystemExit — the set guards gold cleanup, lines must not be lost silently.
    model — a homograph (the context decides; the gold is not touched either way);
    model-mask — a brand word with a Russian trace («Тильда», «Сбербанк»):
    the mechanics hands it to the model, the gold is only mask, never keep."""
    default = path is None
    path = path or os.path.join(DATA_DIR, REGRESS_FILE)
    out: dict = {}
    if default and not os.path.isfile(path):
        return out                 # the local delivery has no set — empty, no exceptions
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            if line.startswith("#") or not line.strip():
                continue
            cells = line.rstrip("\n").split("\t")
            if len(cells) < 2 or cells[1] not in REGRESS_EXPECT:
                raise SystemExit(f"lexicon: {path}:{n}: expected "
                                 f"«form\\t{'|'.join(REGRESS_EXPECT)}…»")
            key = cells[0].strip().lower()
            if not key or key in out:
                raise SystemExit(f"lexicon: {path}:{n}: empty or repeated "
                                 f"form {cells[0]!r}")
            out[key] = (cells[1], cells[2] if len(cells) > 2 else "", cells[0])
    return out


def needs_model(literal: str, freq=None) -> tuple:
    """(True, why) — the mechanics does not mask the literal blindly (the model decides):
    all words are plain, or the words with name evidence are lower-case in the corpus
    (freq — the run's state/mine_freq.json, {word: count}). (False, '') —
    everything else, including any word outside the dictionaries and a name without corpus
    evidence («Женя», «Волк», «Mark», «John Smith» — stay mask)."""
    lit = str(literal or "").strip()
    if not lit:
        return False, ""
    if is_owner_tool(lit):
        return True, "international tool (owner's decision 2026-10-03)"
    if lit.casefold() in _curated():
        return True, "ordinary word/term"
    words = _words(lit)
    if not words:
        return False, ""
    kinds = [word_kind(w) for w in words]
    if any(k == "unknown" for k in kinds):
        return False, ""
    names = [w for w, k in zip(words, kinds) if k == "name"]
    if not names:
        return True, "ordinary word/term"
    if all(lc_dominant(w, freq) for w in names):
        return True, (f"common noun by the corpus (lower-case ≥{LC_DOMINANCE}× "
                      "upper-case)")
    return False, ""
