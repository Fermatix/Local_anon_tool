@lru_cache(maxsize=1)
def entities() -> tuple:
    """Entities of the generated dictionary: a tuple of dict(kind, canonical, seed, flags, forms,
    exact) — the order is deterministic (as in the file), forms of one entity are grouped.
    knob=colloq entries are included (the view without them — lookup(colloq=False))."""
    return _all_entities()


def disabled_canonicals() -> frozenset:
    """Canons of entries disabled for the process lifetime (ENV_DISABLED, separated by «|»; the key is norm);
    empty or «0» — nothing."""
    raw = os.environ.get(ENV_DISABLED, "").strip()
    if raw in ("", "0"):
        return frozenset()
    return frozenset(norm(x) for x in raw.split("|") if norm(x))


def reset_caches() -> None:
    """Reset the dictionary caches (after ENV_DISABLED changes in this process — conveyor.group)."""
    for fn in (_all_entities, entities, _exact_spellings, _exact_spellings_plain, _index,
               _entity_index, _entity_index_core, _plain_ok_names, _rules):
        fn.cache_clear()


def data_available() -> bool:
    """Whether the generated dictionary data/ru_trace.tsv exists. The local delivery does not have it
    (DESIGN.md 3.3): the dictionary is off — without exceptions or warnings, the main
    pipeline finishes the job."""
    return os.path.isfile(DATA_PATH)


@lru_cache(maxsize=1)
def _all_entities() -> tuple:
    if not data_available():
        return ()
    groups: dict = {}
    order = []
    disabled = disabled_canonicals()
    with open(DATA_PATH, encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#") or line.startswith("kind\t"):
                continue
            f = line.split("\t")
            if len(f) != 5:
                raise SystemExit(f"ru_trace: {DATA_PATH}:{n}: {len(f)} columns, expected 5")
            kind, canon, seed, form, flags = f
            if kind not in KIND_ORDER or not form:
                raise SystemExit(f"ru_trace: {DATA_PATH}:{n}: malformed line")
            if disabled and norm(canon) in disabled:
                continue                      # ENV_DISABLED: like the disabled flag in the source
            fl = _parse_flags(flags, f"{DATA_PATH}:{n}")
            # one entity = (kind, canon, case sensitivity, homonym policy): lines
            # of one canon with different declinability (Орехово-Зуево declinable + indeclinable)
            # are merged into one rule
            key = (kind, canon, "exact" in fl, fl.get("hom"), fl.get("ctx"), fl.get("knob"))
            if key not in groups:
                groups[key] = {"kind": kind, "canonical": canon, "seed": seed, "flags": fl,
                               "exact": "exact" in fl, "forms": []}
                order.append(key)
            if form not in groups[key]["forms"]:
                groups[key]["forms"].append(form)
    return tuple(groups[k] for k in order)


@lru_cache(maxsize=1)
def _exact_spellings() -> frozenset:
    return frozenset(f for e in entities() if e["exact"] for f in e["forms"])


@lru_cache(maxsize=1)
def _exact_spellings_plain() -> frozenset:
    """Exact spellings of unambiguous (non-homonym) entries — for kind(): a spelling that only
    a homonym has (lowercase «1с» of hom=nctx) is decided by the rule's context, not by the API."""
    return frozenset(f for e in entities() if e["exact"] and not e["flags"].get("hom")
                     for f in e["forms"])


def _knob(env_name: str, value=None) -> bool:
    raw = os.environ.get(env_name, "") if value is None else value
    raw = str(raw).strip()
    if raw in ("", "0"):
        return False
    if raw == "1":
        return True
    raise SystemExit(f"{env_name}={raw!r}: expected 0 or 1")


@lru_cache(maxsize=1)
def _index() -> dict:
    """{norm(form): (kind, homonym?)} — for the API; exact forms are also by norm (case — in the API)."""
    idx: dict = {}
    for e in entities():
        hom = e["flags"].get("hom") or None      # homonym policy (caps|ctx|ctxany) or None
        for f in e["forms"]:
            k = norm(f)
            prev = idx.get(k)
            # an unambiguous entry beats a homonym one; on a tie — the first one (determinism)
            if prev is None or (prev[1] and not hom):
                idx[k] = (e["kind"], hom, e["exact"], f)
    return idx


_LAW_RX = (
    r"\d{1,4}-ФЗ|ФЗ-\d{1,4}|"
    r"(?:ГК|НК|ТК|УК|ЖК|АПК|ГПК|БК|ЗК|УПК|КоАП)[^\S\r\n]+РФ|КоАП|"
    r"(?:ГОСТ|СНиП|СанПиН)(?:[^\S\r\n]?Р)?(?:[^\S\r\n]?(?:ИСО|ISO|МЭК|IEC)(?:/(?:ИСО|ISO|МЭК|IEC))?)?"
    r"(?:[^\S\r\n]?\d[\d.\-/]*\d)?"
)
_LAW_FULL = re.compile(r"(?:" + _LAW_RX + r")\w{0,3}")


def kind(form: str) -> str | None:
    """The Russian trace kind of the form or None. A homonym (Магнит/магнит…) — only capitalized;
    currency/regulations — only with the knobs on (as for masking)."""
    s = str(form or "").strip()
    if not s:
        return None
    if _knob(ENV_LAWS) and _LAW_FULL.fullmatch(" ".join(s.split())):
        return "law"
    hit = _index().get(norm(s))
    if hit is None:
        return None
    k, hom, exact, orig = hit
    if hom in ("ctx", "ctxany", "nctx"):
        # a strict homonym is decided ONLY by context («HSE requirements», «МИР» without
        # a payment context, «(WB)» — the rule keeps them); without context the API does not count it as a trace,
        # otherwise verify/audit would see a "leak" where the rule deliberately left the word.
        # nctx («1с», «hh») — the same: the rule always masks, except in a time context, which
        # the API cannot see without text (the rule deliberately leaves «таймаут 1с»)
        return None
    if hom:
        # A homonym cannot be resolved without context («Точка доступа» / the «Точка» bank, «Магнит на
        # холодильнике» / the «Магнит» chain): the API — for audit/verification/gold veto, where there is no
        # context — counts as a trace only the BRAND spelling: CAPS (СОПКА, ЭПОС) or an inner
        # capital (МегаФон, ВиСи). A plain «Магнит»/«Точка» is not a trace for the API (the owner's
        # keep decision on «Точка» in gold stays in force); in text, homonyms are masked by
        # the context rules of rules().
        letters = [ch for ch in s if ch.isalpha()]
        brand = len(letters) >= 2 and (all(ch.isupper() for ch in letters)
                                        or any(ch.isupper() for ch in letters[1:]))
        if not brand:
            return None
    if exact and " ".join(s.split()) != orig \
            and " ".join(s.split()) not in _exact_spellings_plain():
        return None                       # exact seeds (ВК/WB/СБП…) — only the listed spellings
    if k == "currency" and not _knob(ENV_CURRENCY):
        return None
    return k


def is_trace(form: str) -> bool:
    """True — the form is a Russian trace (see kind); geo_foreign is not a trace (False)."""
    k = kind(form)
    return k is not None and k != "geo_foreign"


def is_masked(form: str) -> bool:
    """True — the dictionary ALWAYS masks the form, without context: a Russian trace (is_trace) or
    foreign geo (geo_foreign). The owner's policy: geo and trace are always masked, a keep by
    a person/gold does not protect them — this is the predicate of the veto filters (conveyor.ru_trace_scan)."""
    return kind(form) is not None


def _build_entity_index(ents) -> dict:
    idx: dict = {}
    for e in ents:
        for f in e["forms"]:
            k = norm(f)
            prev = idx.get(k)
            if prev is None or ("hom" in prev["flags"] and "hom" not in e["flags"]):
                idx[k] = e
    return idx


@lru_cache(maxsize=1)
def _entity_index() -> dict:
    return _build_entity_index(entities())


@lru_cache(maxsize=1)
def _entity_index_core() -> dict:
    """The index without knob=colloq entries (packgen, verify and mine)."""
    return _build_entity_index(e for e in _all_entities() if e["flags"].get("knob") != "colloq")


def lookup(form: str, colloq: bool = True) -> dict | None:
    """The dictionary entity by form WITHOUT the capitalization rule (packgen: to know whether a brand is a homonym,
    regardless of the case of the approved literal). None — the form is not in the dictionary.
    colloq=False — without colloquial knob=colloq entries: the dictionary masks them only by
    context, and they do not override the run's verdict — packgen, verify and mine see the dictionary without
    them."""
    return (_entity_index() if colloq else _entity_index_core()).get(norm(form))


