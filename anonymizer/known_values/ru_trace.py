# --------------------------------------------------------------------------- normalization
_DASH = re.compile(r"[‐-―−]")
_DASHES = frozenset("‐‑‒–—―−")
_EDGE = " \t\r\n\"'«»“”„()[]{}<>.,;:!?"


def norm(form: str) -> str:
    """Comparison key: casefold, ё→е, dashes → hyphen, spaces collapsed, edges without punctuation.
    The hot path of the audit scanner (conveyor/ru_trace_scan: millions of candidates) — no regex
    while the string has no dashes."""
    s = str(form)
    if not _DASHES.isdisjoint(s):
        s = _DASH.sub("-", s)
    s = s.casefold()
    if "ё" in s:
        s = s.replace("ё", "е")
    if "  " in s or "\t" in s or "\n" in s or "\r" in s or "\xa0" in s:
        s = " ".join(s.split())
    return s.strip(_EDGE)


def store_form(form: str) -> str:
    """The form for ru_trace.tsv: like norm, but ё is KEPT — the rule builds explicit ё/е
    variants (a [её] class in the regex broke prefilter probes, the rule went to a full scan)."""
    s = str(form)
    if not _DASHES.isdisjoint(s):
        s = _DASH.sub("-", s)
    s = " ".join(s.casefold().split())
    return s.strip(_EDGE)


def translit(word: str) -> str:
    """The same translit as packgen.translit (the ORG token seed matches the pack)."""
    return "".join(TRANSLIT.get(ch, ch) for ch in word.lower())


def seed_of(kind: str, canonical: str) -> str:
    return translit(canonical).lower() if kind in ORG_KINDS else ""


