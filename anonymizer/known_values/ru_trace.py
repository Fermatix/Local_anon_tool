# --------------------------------------------------------------------------- rules
# Dictionary boundaries. Latin: «\» on the left is a boundary unless followed by a JSON escape letter
# (the path «C:\Users\spb» is masked, the escape «\nsk» is not). Strict ones (short Latin ≤4 chars and
# case-sensitive seeds): «_» is part of the word (VK_SUCCESS, PERM_DENIED, has_perm — code, not a trace).
# (tg audit): the escape letter is CASE-sensitive (under re.IGNORECASE «\Bitrix» of a PHP path was read
# as the escape «\b» and not masked); after an EVEN number of «\» (an escaped JSON backslash:
# «\\srv\\bitrix\\modules») a letter is the start of a word, not an escape.
# (tg audit: 6 findings of «bitrix» in Windows paths): the Telegram export goes through the structural
# profile — rules see the DECODED string, where «\» is single, and «\bitrix» was read as the escape «\b».
# Only real chat escapes count as escapes: \n \t \r and \uXXXX; \b \f (backspace/form feed)
# do not occur in chats, \v does not exist in JSON — after them a letter is again the start of a word.
_ESC_L = r"(?:(?<=\\)(?!(?-i:[ntr]|u[0-9A-Fa-f]{4}))|(?<=[^\\]\\\\)|(?<=[^\\]\\\\\\\\))"
_LL = r"(?:" + _B._ESC + r"|(?<![" + _B._ALNUM + r"\\])|" + _ESC_L + r")"
_SL = r"(?:" + _B._ESC + r"|(?<![" + _B._ALNUM + r"_\\])|" + _ESC_L + r")"
_SCL = r"(?:" + _B._ESC + r"|(?<![" + _B._ALNUM + r"_]))"
_SR = r"(?![" + _B._ALNUM + r"_])"
SHORT_LAT = 4


def strict_form(form: str) -> bool:
    """The form is masked with strict boundaries («_» is part of the word): short Latin
    (≤SHORT_LAT chars) or the spelling of a case-sensitive seed. The audit/verification scanner
    (conveyor.ru_trace_scan) does not count such a form inside an identifier as a trace — like the rule."""
    s = " ".join(str(form or "").split())
    if s in _exact_spellings():
        return True
    return bool(s) and len(s) <= SHORT_LAT and not _has_cyr(s)


def _form_rx(form: str) -> str:
    """The regex of one form: a space — any horizontal one, a dash — any; the rest literally
    (the literal prefix is needed by the prefilter — engine probes are derived from the parsed regex)."""
    out = []
    for ch in form:
        if ch == " ":
            out.append(r"[^\S\r\n]+")
        elif ch == "-":
            out.append(r"[-‐-―]")
        else:
            out.append(re.escape(ch))
    return "".join(out)


def _with_yo(forms) -> list:
    """Forms + an «е» variant for forms with «ё» (Орёл/Орел, Пятёрочка/Пятерочка)."""
    out = set(forms)
    out.update(f.replace("ё", "е").replace("Ё", "Е") for f in forms if "ё" in f or "Ё" in f)
    return sorted(out)


def _alt(forms) -> str:
    return "|".join(_form_rx(f) for f in sorted(set(forms), key=lambda x: (-len(x), x)))


def _needs(forms) -> tuple:
    """The rule's needs: the first words of the forms (up to a space/dash) — at least one must be in
    the text under any substitution (a space/dash in the regex is wider than the literal, hence not the whole form).
    A cheap condition for short seeds (РФ, ВК, S7) that have no probes of their own."""
    return tuple(sorted({re.split(r"[ \-]", f, maxsplit=1)[0] for f in forms if f}))


def _has_cyr(s: str) -> bool:
    return any("а" <= ch.lower() <= "я" or ch.lower() == "ё" for ch in s)


def _initial(text: str, a: int) -> bool:
    """Start of a sentence/line/value left of position a (quotes and list markers are skipped)."""
    j = a - 1
    while j >= 0 and text[j] in _SKIP_LEFT:
        j -= 1
    if j < 0:
        return True
    c = text[j]
    if c in "\n\r.!?…:;":
        return True
    return c in "ntr" and j >= 1 and text[j - 1] == "\\"     # JSONL escape \n \t \r


def _quoted(text: str, a: int, b: int) -> bool:
    return a > 0 and b < len(text) and text[a - 1] in _OPEN_Q and text[b] in _CLOSE_Q


def _sentence_window(text: str, a: int, b: int) -> str:
    left = text[max(0, a - _WINDOW):a]
    last = None
    for last in _SENT.finditer(left):
        pass
    if last is not None:
        left = left[last.end():]
    right = text[b:b + _WINDOW]
    nxt = _SENT.search(right)
    if nxt is not None:
        right = right[:nxt.start()]
    return left + " " + right


def _geo_left(text: str, a: int):
    """A place preposition in a 30-char window on the left (like the engine gate, context.left_hit): search in
    the full text with pos/endpos — \\b at the left edge of the window sees the letter before the window; a slice gave «в»
    from «Петров» and «г.» from «мг.» (spaces before the form — an extra geo mask)."""
    return _GEO_LEFT.search(text, max(0, a - 30), a)


def _raw_right(rx, text: str, b: int, w: int):
    """The right window [b, b+w) without a sentence boundary (like context.right_hit, but the window spans lines):
    the match is entirely in the window, while lookahead and \\b at the right edge see ctx_ahead chars past
    the window — endpos = the window edge gave «счет» from «счетчик», BANKNEAR's сч[её]т[аеуо]?\\b fired
    on the fragment."""
    lim = min(len(text), b + w)
    stop = min(len(text), lim + _C.ctx_ahead(rx))
    if stop <= lim:                    # the window hits the end of the text — as before
        return rx.search(text, b, lim)
    return _C._within(rx, stop - lim).search(text, b, stop)


def _ctx_hit(text: str, a: int, b: int, names) -> bool:
    win = None
    for name in names:
        if name == "GEO":
            if _geo_left(text, a) or _GEO_RIGHT.match(text, b):
                return True
            continue
        if name in _NOT_WINDOW:
            continue
        w = _RAW_WINDOW.get(name)
        if w:
            if _CTX[name].search(text, max(0, a - w), a) or _raw_right(_CTX[name], text, b, w):
                return True
            continue
        if win is None:
            win = _sentence_window(text, a, b)
        if _CTX[name].search(win):
            return True
    return False


def _token_guard(m) -> bool:
    return is_own_token(m.group(1), part=True)       # only our token


# (tg audit: «Нижний» stayed next to «GEO_REDACTED» six times over two rounds): a pack rule for a part
# of a compound place name («Новгород» with a mask verdict) fires BEFORE the dictionary, and a geo homonym without
# its own context stayed as a fragment. A geo token right next to it (via a space/hyphen) is the geo context.
_GEO_TOKEN_RIGHT = re.compile(r"[^\S\r\n]*[-‐‑–—]?[^\S\r\n]*" + re.escape(P.GEO) + r"(?![A-Za-z0-9_])")
_GEO_TOKEN_LEFT = re.compile(r"(?<![A-Za-z0-9_])" + re.escape(P.GEO) + r"[^\S\r\n]*[-‐‑–—]?[^\S\r\n]*$")


def _geo_token_near(text: str, a: int, b: int) -> bool:
    return bool(_GEO_TOKEN_RIGHT.match(text, b)
                or _GEO_TOKEN_LEFT.search(text, max(0, a - len(P.GEO) - 4), a))


def _except_hit(text: str, a: int, names: tuple) -> bool:
    """A set phrase right next to it on the left (the except= flag): the form is an ordinary word, keep."""
    return any(_EXCEPT_LEFT[n].search(text, max(0, a - 12), a) for n in names)


def _mult_hit(text: str, a: int, b: int) -> bool:
    """The MULT label: the form is a multiplier («в х5 раз», «х2, х5 и х10»), keep. The window of a neighbouring
    multiplier is within the sentence: the structural profile feeds neighbouring messages to the rules via
    a line break (structured.engine.SEP), and «х2» from a neighbouring message does not make «х5» a multiplier."""
    if _MULT_RIGHT.match(text, b):
        return True
    lo = max(0, a - _MULT_WINDOW)
    for last in _SENT.finditer(text, lo, a):
        lo = last.end()
    hi = min(len(text), b + _MULT_WINDOW)
    nxt = _SENT.search(text, b, hi)
    if nxt is not None:
        hi = nxt.start()
    return bool(_MULT_NEAR.search(text, lo, a) or _MULT_NEAR.search(text, b, hi))


def _with_except(guard, names: tuple):
    """The entry's guard + set-phrase exceptions (except=): True = leave as is."""
    def g(m) -> bool:
        return guard(m) or _except_hit(m.string, m.start(1), names)
    g.__name__ = f"{guard.__name__}_except_{'_'.join(names)}"
    return g


def _homonym_guard(policy: str, names: tuple):
    """A guard for a homonym: True = leave as is (see the module header)."""
    def guard(m) -> bool:
        s = m.group(1)
        if is_own_token(s, part=True):
            return True
        letters = [ch for ch in s if ch.isalpha()]
        text, a, b = m.string, m.start(1), m.end(1)
        if "GEO" in names and letters and _geo_token_near(text, a, b):
            return False                          # part of a compound place name next to a geo token
        if "NO_PHRASE" in names and _CTX["NO_PHRASE"].match(text, b):
            return True                           # «Точка входа/роста…» — a phrase, not a brand
        if "MULT" in names and _mult_hit(text, a, b):
            return True                           # «в х5 раз» — a multiplier, not the chain
        if policy == "nctx":
            # owner's decision: lowercase «1с»/«hh» in chats are almost always 1С and HeadHunter
            # (tg: time 2 of 112, time format 2 of 472): ALWAYS mask, except with the entry's context
            # nearby — time («таймаут 1с», «задержка 1с»), time format («hh:mm», yyyy)
            if not letters:
                return True
            return _ctx_hit(text, a, b, names)
        if policy == "ctxany":
            # a short seed that is also written in lowercase («заказала на вб»): mask only
            # with the entry's context, case does not decide («write-back (WB)» without context — keep)
            if not letters:
                return True
            if _LABEL.match(text, b):
                return "LABEL" not in names       # «1C: Управление…» — a product, not a caption
            return not _ctx_hit(text, a, b, names)
        if not letters or not letters[0].isupper():
            return True                           # lowercase — an ordinary word
        if _LABEL.match(text, b):
            return True                           # a field caption «Почта: …», «Мир:» — not a brand
        if policy == "ctx":
            return not _ctx_hit(text, a, b, names)
        if (len(letters) >= 2 and all(ch.isupper() for ch in letters)) \
                or any(ch.isupper() for ch in letters[1:]) or _quoted(text, a, b):
            return False                          # CAPS / МегаФон / «Магнит» — a brand
        if _initial(text, a):
            return not _ctx_hit(text, a, b, ("BRAND",) + names)
        return False                              # a capital in mid-sentence — a proper noun
    guard.__name__ = f"homonym_{policy}_{'_'.join(names)}"
    return guard


def _mask_for(e: dict):
    if e["kind"] in GEO_KINDS:
        return lambda m: P.GEO
    if e["kind"] == "currency":
        def cur(m):
            s, a, b = m.string, m.start(), m.end()
            left = " " if a > 0 and s[a - 1].isalnum() else ""
            right = " " if b < len(s) and s[b].isalnum() else ""
            return left + P.CURRENCY + right
        return cur
    seed = e["seed"]
    return lambda m: mint.tag("ORG", seed)


def _entity_name(e: dict) -> str:
    """The base name of the entity's rules (without the :cyr/:lat/:lat-short tail)."""
    name = f"rutrace:{e['kind']}:{e['seed'] or translit(e['canonical']).lower()}"
    if e["exact"]:
        name += ":exact"
    hom = e["flags"].get("hom")
    if hom:
        # a canon may have two lines — an unambiguous one and a homonym (1С in Cyrillic / 1C in Latin)
        name += f":hom-{hom}"
    return name


@lru_cache(maxsize=1)
def _plain_ok_names() -> frozenset:
    return frozenset(_entity_name(e) for e in entities() if "plain_ok" in e["flags"])


def rule_plain_ok(rule_name: str) -> bool:
    """The dictionary rule belongs to an entry with the plain_ok flag — the mask of a form that coincides with
    an ordinary word is deliberate (a decision of the owner/dictionary curator): the magnitude safeguard
    "the dictionary spoils an ordinary word" does not stop such a rule."""
    return str(rule_name).rsplit(":", 1)[0] in _plain_ok_names()


def _entity_rules(e: dict) -> list:
    name = _entity_name(e)
    hom = e["flags"].get("hom")
    names = tuple(x for x in str(e["flags"].get("ctx") or "").split("+") if x)
    guard = _homonym_guard(hom, names) if hom else _token_guard
    exc = tuple(x for x in str(e["flags"].get("except") or "").split("+") if x)
    if exc:
        guard = _with_except(guard, exc)
    flags = 0 if e["exact"] else re.IGNORECASE
    mask = _mask_for(e)
    forms = _with_yo(e["forms"])
    cyr = [f for f in forms if _has_cyr(f)]
    lat = [f for f in forms if not _has_cyr(f)]
    rules = []
    if e["kind"] == "currency":
        lb, rb = r"(?<![A-Za-zА-Яа-яЁё])", r"(?![A-Za-zА-Яа-яЁё0-9])"
        rules.append(Rule(name, re.compile(lb + "(" + _alt(forms) + ")" + rb, flags),
                          mask=mask, value_group=1, guard=_token_guard, confidence="high",
                          needs=_needs(forms)))
        return rules
    if cyr:
        cl, cr = (_SCL, _SR) if e["exact"] else (CL, CR)
        rules.append(Rule(name + ":cyr", re.compile(cl + "(" + _alt(cyr) + ")" + cr, flags),
                          mask=mask, value_group=1, guard=guard, confidence="high",
                          needs=_needs(cyr)))
    if lat:
        # a Latin brand with a Russian case ending («в Yandexе») — the whole ending goes under the token
        tail = r"(?:[а-яё]{1,4})?" if not e["exact"] else ""
        short = [f for f in lat if e["exact"] or len(f) <= SHORT_LAT]
        long_ = [f for f in lat if f not in short]
        if long_:
            rules.append(Rule(name + ":lat",
                              re.compile(_LL + "((?:" + _alt(long_) + ")" + tail + ")" + R, flags),
                              mask=mask, value_group=1, guard=guard, confidence="high",
                              needs=_needs(long_)))
        if short:
            rules.append(Rule(name + ":lat-short",
                              re.compile(_SL + "((?:" + _alt(short) + ")" + tail + ")" + _SR, flags),
                              mask=mask, value_group=1, guard=guard, confidence="high",
                              needs=_needs(short)))
    return rules


# fused ecosystem spellings («ЯндексGo», «Яндекс360», «СберПэй», «SberPay») and «Я.Маркет»:
# a stem + a capital/digit right after it — the stem's token. «сбережения»/«Яндексе» are not affected
# (a lowercase letter after the stem). Placed AFTER the entity rules: «СберМаркет» takes its token earlier.
_PREFIX_STEMS = (("Яндекс", "Яндекс"), ("Яндекс", "Yandex"), ("Сбер", "Сбер"), ("Сбер", "Sber"),
                 ("Тинькофф", "Тинькофф"), ("Тинькофф", "Tinkoff"),
                 # (tg audit): code identifiers — a stem + a capital/digit from the start
                 # of the identifier («BitrixShippingClient», «mindboxClientKey», «yandexSearchArgs»)
                 ("Битрикс", "Bitrix"), ("Битрикс", "bitrix"), ("Mindbox", "Mindbox"),
                 ("Mindbox", "mindbox"), ("Яндекс", "yandex"), ("Сбер", "sber"))
# a camelCase segment INSIDE an identifier («SyncBitrixQueue», «XBitrixAdapter», «getYandexToken»):
# a stem with a capital after a lowercase letter/digit (or a capital — «XBitrix…»), then not a lowercase letter.
# Owner's policy: only the trace segment is masked, the rest of the identifier is intact.
_CAMEL_STEMS = (("Битрикс", "Bitrix"), ("Mindbox", "Mindbox"), ("Яндекс", "Yandex"), ("Сбер", "Sber"),
                ("Тинькофф", "Tinkoff"))
_CAP_TAIL = r"(?=[A-ZА-ЯЁ0-9])[A-Za-zА-Яа-яЁё0-9]+"
# (tg audit): a time zone glued to a digit («11мск», «10:00мск», «13екб»; tg: 242 and 34
# occurrences past the mask) — the dictionary boundary (a digit on the left is part of the word) did not take it. After a digit
# a city abbreviation is a time zone/city, no homonyms.
_AFTER_DIGIT = (("Мск", ("мск", "msk")), ("ЕКБ", ("екб", "ekb")))
# «5Ka» as a snake_case/file name segment («promo_in_5Ka.docx», «5Ka_240101») — for an exact short
# form «_» is part of the word (VK_SUCCESS), but «5Ka» is unambiguous: the segment at «_» is a trace, the rest is intact.
_SNAKE_STEMS = (("5ka", "5Ka"), ("5ka", "5ka"))


def _prefix_rules() -> list:
    out = []
    seen = set()
    for canon, stem in _PREFIX_STEMS:
        e = lookup(canon)
        if e is None or e["kind"] not in ORG_KINDS or "disabled" in e["flags"]:
            continue
        left = CL if _has_cyr(stem) else _LL
        script = "cyr" if _has_cyr(stem) else "lat"
        lc = "-lc" if stem[:1].islower() else ""      # «Bitrix» and «bitrix» — different rules
        name = f"rutrace:org:{e['seed']}:prefix:{script}:{translit(stem).lower()}{lc}"
        if name in seen:
            continue
        seen.add(name)
        seed = e["seed"]
        out.append(Rule(name, re.compile(left + "(" + re.escape(stem) + _CAP_TAIL + ")" + R),
                        mask=lambda m, s=seed: mint.tag("ORG", s), value_group=1,
                        guard=_token_guard, confidence="high", needs=(stem,)))
    for canon, stem in _CAMEL_STEMS:
        e = lookup(canon)
        if e is None or e["kind"] not in ORG_KINDS or "disabled" in e["flags"]:
            continue
        seed = e["seed"]
        out.append(Rule(f"rutrace:org:{seed}:camel:{translit(stem).lower()}",
                        re.compile(r"(?:(?<=[a-z0-9])|(?<=[A-Z]))(" + re.escape(stem) + r")(?![a-z])"),
                        mask=lambda m, s=seed: mint.tag("ORG", s), value_group=1,
                        guard=_token_guard, confidence="high", needs=(stem,)))
    for canon, stem in _SNAKE_STEMS:
        e = lookup(canon)
        if e is None or e["kind"] not in ORG_KINDS or "disabled" in e["flags"]:
            continue
        seed = e["seed"]
        lc = "-lc" if stem.islower() else ""
        out.append(Rule(f"rutrace:org:{seed}:snake:{translit(stem).lower()}{lc}",
                        re.compile(r"(?:(?<=_)|(?<![" + _B._ALNUM + r"_])(?=" + re.escape(stem) + r"_))("
                                   + re.escape(stem) + r")(?![" + _B._ALNUM + r"])"),
                        mask=lambda m, s=seed: mint.tag("ORG", s), value_group=1,
                        guard=_token_guard, confidence="high", needs=(stem,)))
    # (owner's decision): lowercase «точка» right after «банк» is the bank («через банк точка»,
    # «счёт: банк точка»; tg: 10 occurrences, all the bank); any other lowercase «точка» is a word
    e = lookup("Точка")
    if e is not None and "disabled" not in e["flags"]:
        out.append(Rule(f"{_entity_name(e)}:after-bank",
                        re.compile(r"(?:(?<=банк )|(?<=банка )|(?<=банке )|(?<=банку ))"
                                   r"(точк(?:ой|ою|а|и|е|у))" + R, re.IGNORECASE),
                        mask=_mask_for(e), value_group=1, guard=_token_guard,
                        confidence="high", needs=("точк",)))
    # (tg samples): «в контакте» written separately in lowercase meaning the social network («приложение в
    # контакте», «мини приложение в контакте») — the ВКонтакте seed; «контакте» is masked, the preposition stays.
    # The ordinary «в контакте с кем-то» is a word: mask only with social network words nearby (VKAPP) and not before «с/со»
    e = lookup("ВКонтакте")
    if e is not None and "disabled" not in e["flags"]:
        seed = e["seed"]

        def _vk_guard(m) -> bool:
            text, a, b = m.string, m.start(1), m.end(1)
            if _token_guard(m) or re.match(r"[^\S\r\n]+со?(?![А-Яа-яЁё])", text[b:b + 5], re.IGNORECASE):
                return True
            return not _ctx_hit(text, a, b, ("VKAPP",))
        out.append(Rule(f"{_entity_name(e)}:v-kontakte",
                        re.compile(r"(?<=[вВ][ \xa0])(?<![А-Яа-яЁёA-Za-z0-9_][вВ][ \xa0])(контакте)" + R,
                                   re.IGNORECASE),
                        mask=lambda m, s=seed: mint.tag("ORG", s), value_group=1, guard=_vk_guard,
                        confidence="high", needs=("контакте",)))
    for canon, forms in _AFTER_DIGIT:
        e = lookup(canon)
        if e is None or "disabled" in e["flags"]:
            continue
        out.append(Rule(f"{_entity_name(e)}:after-digit",
                        re.compile(r"(?<=[0-9])(" + "|".join(forms) + r")" + R, re.IGNORECASE),
                        mask=_mask_for(e), value_group=1, guard=_token_guard,
                        confidence="high", needs=forms))
    e = lookup("Яндекс")
    if e is not None:
        seed = e["seed"]
        out.append(Rule(f"rutrace:org:{seed}:prefix:ya-dot",
                        re.compile(r"(?<![" + _B._ALNUM + r"_.])(Я\." + _CAP_TAIL + ")" + R),
                        mask=lambda m, s=seed: mint.tag("ORG", s), value_group=1,
                        guard=_token_guard, confidence="high", needs=("Я.",)))
    return out


def _law_rules() -> list:
    rx = re.compile(r"(?<![\w-])(" + _LAW_RX + r")(?![\w-])")
    return [Rule("rutrace:law", rx, mask=lambda m: P.LAW, value_group=1,
                 guard=_token_guard, confidence="high",
                 needs=("ФЗ", "РФ", "КоАП", "ГОСТ", "СНиП", "СанПиН"))]


def law_rules() -> list:
    """Regulation rules (the laws knob). The conveyor places them FIRST, before the detectors: otherwise the legal-form
    rule of the organization detector took «152» from «ГК РФ и 152-ФЗ» into an ORG token."""
    return _law_rules()


@lru_cache(maxsize=8)
def _rules(currency: bool, laws: bool) -> tuple:
    out = list(_law_rules()) if laws else []   # «ГК РФ» as a whole — before the country «РФ»
    ents = [e for e in entities() if e["kind"] != "currency" or currency]
    # longer entities first: «Яндекс Маркет» before «Яндекс», «Нижний Новгород» before «Нижний»
    ents.sort(key=lambda e: (-max(len(f) for f in e["forms"]), KIND_ORDER.index(e["kind"]),
                             e["canonical"], e["exact"]))
    for e in ents:
        out.extend(_entity_rules(e))
    out.extend(_prefix_rules())
    names = [r.name for r in out]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise SystemExit(f"ru_trace: duplicate rule names {dup[:5]} — fix the source")
    return tuple(out)


def rules(currency: bool = False, laws: bool = False) -> list:
    """Dictionary rules (cached per process)."""
    return list(_rules(bool(currency), bool(laws)))


def config_from_env(cfg: dict | None = None) -> dict:
    """Normalized config["ru_trace"] with env overrides (called by config.load)."""
    base = {"enabled": True, "currency": False, "laws": False}
    if isinstance(cfg, bool):                 # "ru_trace": false — the short form
        cfg = {"enabled": cfg}
    if cfg is not None and not isinstance(cfg, dict):
        raise SystemExit(f"config: ru_trace must be an object or true/false, got {cfg!r}")
    cfg = dict(cfg or {})
    unknown = sorted(set(cfg) - set(base))
    if unknown:
        raise SystemExit(f"config: ru_trace: unknown keys {unknown} (known: {sorted(base)})")
    for k, v in cfg.items():
        if not isinstance(v, bool):
            raise SystemExit(f"config: ru_trace.{k} must be true/false, got {v!r}")
    base.update(cfg)
    if os.environ.get(ENV_ON, "").strip() != "":
        base["enabled"] = _knob(ENV_ON)
    if not data_available():
        base["enabled"] = False           # no dictionary in the delivery — silently off
    if os.environ.get(ENV_CURRENCY, "").strip() != "":
        base["currency"] = _knob(ENV_CURRENCY)
    if os.environ.get(ENV_LAWS, "").strip() != "":
        base["laws"] = _knob(ENV_LAWS)
    return base
