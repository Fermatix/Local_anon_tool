def _parse_flags(raw: str, where: str) -> dict:
    out: dict = {}
    for item in [x.strip() for x in raw.split(",") if x.strip()]:
        k, _, v = item.partition("=")
        if k not in _FLAG_KEYS:
            raise SystemExit(f"ru_trace: {where}: unknown flag {k!r}")
        out[k] = v if _ else True
    if "infl" in out and out["infl"] not in _INFL:
        raise SystemExit(f"ru_trace: {where}: infl={out['infl']!r} not in {sorted(_INFL)}")
    if "hyph" in out and out["hyph"] not in _INFL - {"none"}:
        raise SystemExit(f"ru_trace: {where}: hyph={out['hyph']!r}")
    if "hom" in out and out["hom"] not in _HOM:
        raise SystemExit(f"ru_trace: {where}: hom={out['hom']!r} not in {'|'.join(_HOM)}")
    if "hom" in out and not out.get("ctx"):
        raise SystemExit(f"ru_trace: {where}: homonym without ctx=")
    for c in str(out.get("ctx") or "").split("+"):
        if c and c not in _CTX:
            raise SystemExit(f"ru_trace: {where}: unknown context {c!r}")
    if "except" in out:
        names = [c for c in str(out["except"]).split("+") if c]
        if not names or any(c not in _EXCEPT_LEFT for c in names):
            raise SystemExit(f"ru_trace: {where}: except={out['except']!r} — expected "
                             f"{'|'.join(sorted(_EXCEPT_LEFT))}[+…]")
    if "exact" in out and "indecl" not in out:
        raise SystemExit(f"ru_trace: {where}: exact without indecl — case-sensitive forms are not inflected")
    if "knob" in out and out["knob"] not in _ROW_KNOBS:
        raise SystemExit(f"ru_trace: {where}: knob={out['knob']!r}")
    if "deriv" in out:
        fam, _, stem = str(out["deriv"]).partition(":")
        if fam not in DERIV_FAMILIES or (_ and not stem.strip()):
            raise SystemExit(f"ru_trace: {where}: deriv={out['deriv']!r} — expected "
                             f"{'|'.join(DERIV_FAMILIES)}[:stem]")
    return out


def parse_src(text: str, path: str = SRC_PATH) -> list:
    """Source lines → [{kind, canonical, variants, flags, flags_raw}] with validation."""
    rows = []
    for n, line in enumerate(text.split("\n"), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        f = line.split("\t")
        if len(f) < 2 or len(f) > 4:
            raise SystemExit(f"ru_trace: {path}:{n}: expected 2–4 columns, got {len(f)}")
        f += [""] * (4 - len(f))
        kind, canon, variants, flags = (x.strip() for x in f)
        if kind not in KIND_ORDER:
            raise SystemExit(f"ru_trace: {path}:{n}: kind {kind!r} not in {KIND_ORDER}")
        if not canon:
            raise SystemExit(f"ru_trace: {path}:{n}: empty canon")
        fl = _parse_flags(flags, f"{path}:{n}")
        if (kind == "currency") != (fl.get("knob") == "currency"):
            raise SystemExit(f"ru_trace: {path}:{n}: currency ⇔ knob=currency")
        var = [v.strip() for v in variants.split("|") if v.strip()]
        if fl.get("knob") == "colloq" and not var:
            # colloq row forms — only its variants (the canon belongs to the main entry)
            raise SystemExit(f"ru_trace: {path}:{n}: knob=colloq without variants")
        rows.append({"kind": kind, "canonical": canon, "flags": fl,
                     "flags_raw": ",".join(sorted(x.strip() for x in flags.split(",") if x.strip())),
                     "variants": var})
    return rows


